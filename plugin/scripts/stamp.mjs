// Writes src/build-info.ts with a build stamp so the running plugin can
// report which build it is (bridge_status -> plugin.build). Runs before
// esbuild; the file is gitignored.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const here = path.dirname(fileURLToPath(import.meta.url));
let rev = "nogit";
try {
  rev = execSync("git rev-parse --short HEAD", { cwd: here, stdio: ["ignore", "pipe", "ignore"] })
    .toString()
    .trim();
} catch {
  // not a git checkout
}
const stamp = `${new Date().toISOString().slice(0, 16).replace("T", " ")} ${rev}`;
writeFileSync(
  path.join(here, "..", "src", "build-info.ts"),
  `// Generated by scripts/stamp.mjs at build time. Do not edit.\nexport const BUILD = ${JSON.stringify(stamp)};\n`,
);
console.log(`stamp: ${stamp}`);
