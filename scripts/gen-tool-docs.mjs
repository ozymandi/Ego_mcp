#!/usr/bin/env node
// Generates skills/figma-mcp/references/tools.md from the live tool
// registrations in dist/server.js, so the skill never drifts from the code.
//
// Usage: node scripts/gen-tool-docs.mjs   (run `npm run build:server` first)

import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { zodToJsonSchema } from "zod-to-json-schema";
import { z } from "zod";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const outFile = path.join(root, "skills", "figma-mcp", "references", "tools.md");

// Group label by the source module that registered the tool.
const GROUPS = [
  ["server.js", "Core: REST reads + plugin bridge"],
  ["tools-canvas.js", "Canvas helpers (plugin)"],
  ["tools-spec.js", "Design spec (plugin)"],
  ["tools-pages.js", "Pages (plugin)"],
  ["tools-components.js", "Components & instances (plugin)"],
  ["tools-variables.js", "Variables (plugin)"],
  ["tools-svg.js", "SVG & icons (plugin)"],
  ["tools-critique.js", "Design critique (plugin + rules)"],
  ["tools-libraries.js", "Variables & libraries (REST)"],
  ["tools-design-system.js", "Design system search (REST + local cache)"],
  ["tools-diagrams.js", "Diagrams (plugin)"],
  ["tools-figjam.js", "FigJam (plugin)"],
  ["tools-filesystem.js", "Filesystem workspaces"],
  ["tools-code-connect.js", "Code Connect"],
  ["tools-help.js", "Help"],
];

const tools = [];
const orig = McpServer.prototype.registerTool;
McpServer.prototype.registerTool = function (name, cfg, cb) {
  // Nearest frame inside dist/ is the module that registered the tool.
  const frame = (new Error().stack ?? "")
    .split("\n")
    .find((l) => /[\\/]dist[\\/]/.test(l)) ?? "";
  const group =
    GROUPS.find(([file]) => frame.includes(file))?.[1] ?? "Other";
  const schema = cfg.inputSchema
    ? zodToJsonSchema(z.object(cfg.inputSchema))
    : { properties: {} };
  tools.push({ name, title: cfg.title, description: cfg.description, schema, group });
  return orig.call(this, name, cfg, cb);
};

process.env.FIGMA_TOKEN ||= "placeholder";
StdioServerTransport.prototype.start = async function () {};
await import(pathToFileURL(path.join(root, "dist", "server.js")).href);

function typeOf(p) {
  if (p.enum) return p.enum.map((v) => `'${v}'`).join(" | ");
  if (p.type === "array") return `${typeOf(p.items ?? {})}[]`;
  if (p.const !== undefined) return `'${p.const}'`;
  return p.type ?? "any";
}

function paramLines(schema) {
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const names = Object.keys(props);
  if (names.length === 0) return "  (no parameters)";
  return names
    .map((n) => {
      const p = props[n];
      const req = required.has(n) ? "" : "?";
      const def = p.default !== undefined ? ` = ${JSON.stringify(p.default)}` : "";
      const desc = p.description ? ` — ${p.description.replace(/\s+/g, " ")}` : "";
      return `  - \`${n}${req}: ${typeOf(p)}${def}\`${desc}`;
    })
    .join("\n");
}

const byGroup = new Map();
for (const t of tools) {
  if (!byGroup.has(t.group)) byGroup.set(t.group, []);
  byGroup.get(t.group).push(t);
}

let md = `# Tool reference — gemma-figma-mcp\n\n`;
md += `Generated by \`scripts/gen-tool-docs.mjs\` from the server's registrations. Do not edit by hand.\n\n`;
md += `${tools.length} tools. Optional parameters end with \`?\`. Colors are hex (\`#0d99ff\`, \`#0d99ffcc\`). Node ids look like \`12:345\`.\n\n`;
for (const [, label] of GROUPS) {
  const list = byGroup.get(label);
  if (!list) continue;
  md += `## ${label}\n\n`;
  for (const t of list) {
    md += `### \`${t.name}\`\n`;
    if (t.description) md += `${t.description.replace(/\s+/g, " ")}\n`;
    md += `${paramLines(t.schema)}\n\n`;
  }
}

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, md);
console.error(`[gen-tool-docs] wrote ${outFile} (${tools.length} tools, ${md.length} chars)`);

// Context cost of the tool list as an MCP client would serialise it.
const wire = JSON.stringify(
  tools.map((t) => ({ name: t.name, description: t.description, inputSchema: t.schema })),
);
const heaviest = tools
  .map((t) => ({ n: t.name, b: JSON.stringify({ d: t.description, s: t.schema }).length }))
  .sort((a, b) => b.b - a.b)
  .slice(0, 8)
  .map((t) => `${t.n}=${t.b}`)
  .join(", ");
console.error(
  `[gen-tool-docs] tool list on the wire: ${wire.length.toLocaleString()} bytes (~${Math.round(wire.length / 3.6).toLocaleString()} tokens). Heaviest: ${heaviest}`,
);
process.exit(0);
